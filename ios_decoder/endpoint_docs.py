"""Human-readable documentation of every endpoint in the decoder's URL table.

The README's "Protobufs by endpoint" tables and its decoded examples are generated from here, so
they cannot drift from :func:`ios_decoder.endpoints.default_table` or from the real decoder output
in ``examples/example_output.txt``.  Each entry of :data:`DOCS` pairs one endpoint
pattern from that table with a plain-English description; the request/response message names
are read from the table itself.  A test (``tests/test_endpoint_docs.py``) fails if an endpoint has
no description, a description has no endpoint, or the README block is out of date.

    python3 -m ios_decoder.endpoint_docs --write   # rewrite the block in README.md
    python3 -m ios_decoder.endpoint_docs --check   # exit 1 if README.md is out of date
"""

