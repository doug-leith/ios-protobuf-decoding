def _by_pattern() -> dict[str, Endpoint]:
    return {e.pattern: e for e in default_table().endpoints}


def _messages(ep: Endpoint, doc: Doc) -> str:
    """The message names for one endpoint: from the table when it names messages, else the handler note."""
    if doc.decoder:
        return doc.decoder
    if ep.pattern == r"gs-loc\.apple\.com/clls/wloc":      # routed by ARPC function ID
        req = " or ".join(f"`{m}` (function {f})" for f, m in sorted(_WLOC_REQUEST_BY_FID.items()))
        rsp = " or ".join(f"`{m}`" for _, m in sorted(_WLOC_RESPONSE_BY_TYPE.items()))
        return f"request: {req}<br>response: {rsp}"
    if ep.pattern.startswith(r"(fbs|api)"):                  # routed by ?type=
        chans = "; ".join(f"`{t}` → `{m}`" for t, (_, m) in fb.FB_TYPE_MAP.items())
        return f"request, by `?type=`: {chans}"
    parts = []
    if ep.request and ep.request.message:
        parts.append(f"request: `{ep.request.message}`")
    if ep.response and ep.response.message:
        parts.append(f"response: `{ep.response.message}`")
    return "<br>".join(parts)


def render_markdown() -> str:
    """The generated README block, from BEGIN to END inclusive."""
    table = _by_pattern()
    begin, end = markers("endpoint-table")
    out = [begin, ""]
    for key, heading, intro in CATEGORIES:
        out += [f"#### {heading}", "", intro, "",
                "| Endpoint | What it is | Messages |", "|---|---|---|"]
        for doc in DOCS:
            if doc.category == key:
                out.append(f"| `{doc.url}` | {doc.purpose} | {_messages(table[doc.pattern], doc)} |")
        out.append("")
    out.append(end)
    return "\n".join(out)


