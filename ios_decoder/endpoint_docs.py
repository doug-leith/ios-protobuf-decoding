def _example_flows() -> dict[str, list[str]]:
    """url -> the decoded request/response lines of each flow in examples/example_output.txt."""
    text = (ROOT / "examples" / "example_output.txt").read_text()
    flows: dict[str, list[str]] = {}
    for chunk in re.split(r"\n(?=timestamp )", text.strip("\n")):
        lines = chunk.splitlines()
        post = next((i for i, l in enumerate(lines) if l.startswith("POST ")), None)
        if post is None:
            continue
        body = [l for l in lines[post:] if not l.startswith("+++")]
        flows[lines[post].split(" ", 1)[1]] = body
    return flows


def render_examples() -> str:
    """The README block of decoded examples, from examples/example_output.txt."""
    flows = _example_flows()
    begin, end = markers("examples")
    out = [begin, ""]
    for frag, heading, sentence, limit in EXAMPLES:
        url = next(u for u in flows if frag in u)
        lines = flows[url]
        shown = lines[:limit] + (["..."] if len(lines) > limit else [])
        out += [f"#### {heading}", "", sentence, "", "```text", *shown, "```", ""]
    out.append(end)
    return "\n".join(out)


def problems() -> list[str]:
    """Mismatches between the endpoint table and DOCS (empty when they agree)."""
    table = _by_pattern()
    docs = [d.pattern for d in DOCS]
    issues = [f"endpoint has no description: {p}" for p in table if p not in docs]
    issues += [f"description has no endpoint: {p}" for p in docs if p not in table]
    issues += [f"duplicate description: {p}" for p in set(docs) if docs.count(p) > 1]
    issues += [f"unknown category {d.category!r}: {d.pattern}" for d in DOCS
               if d.category not in {k for k, _, _ in CATEGORIES}]
    return issues


def readme_path() -> Path:
    return ROOT / "README.md"


def splice(readme_text: str, name: str, block: str) -> str:
    """Replace the generated block called *name* in *readme_text* with *block*."""
    begin, end = markers(name)
    pat = re.compile(re.escape(begin) + r".*?" + re.escape(end), re.S)
    if not pat.search(readme_text):
        raise SystemExit(f"README.md has no '{name}' markers")
    return pat.sub(lambda _: block, readme_text, count=1)


def render_readme(readme_text: str) -> str:
    """*readme_text* with every generated block brought up to date."""
    return splice(splice(readme_text, "endpoint-table", render_markdown()), "examples", render_examples())


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--write", action="store_true", help="rewrite the generated block in README.md")
    g.add_argument("--check", action="store_true", help="exit 1 if README.md is out of date")
    args = ap.parse_args(argv)
    bad = problems()
    if bad:
        print("\n".join(bad), file=sys.stderr)
        return 1
    path = readme_path()
    text = path.read_text()
    new = render_readme(text)
    if args.check:
        if new != text:
            print("README.md generated blocks are out of date; run: python3 -m ios_decoder.endpoint_docs --write",
                  file=sys.stderr)
            return 1
        return 0
    path.write_text(new)
    print(f"updated {path.name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
