def markers(name: str) -> tuple[str, str]:
    """The README comment markers that delimit the generated block called *name*."""
    return (f"<!-- BEGIN {name} (generated by ios_decoder/endpoint_docs.py; do not edit by hand) -->",
            f"<!-- END {name} -->")


@dataclass(frozen=True)
class Doc:
    category: str          # key into CATEGORIES
    url: str               # readable form of the endpoint, shown in the README
    pattern: str           # must equal an Endpoint.pattern in default_table()
    purpose: str           # what the endpoint is for, in plain English
    decoder: str = ""      # for endpoints decoded by a handler instead of a named message


